use super::super::types::PipelineNode;
use super::{PipelineNodeWire, default_prompt_tool_mode, default_total_thoughts};

impl From<PipelineNode> for PipelineNodeWire {
    #[allow(clippy::too_many_lines)]
    fn from(node: PipelineNode) -> Self {
        match node {
            PipelineNode::Workflow {
                id,
                display_label,
                workflow_id,
                acp_client,
                prompt,
                cwd,
                timeout,
                agent_config,
                adopt,
                requires_role,
                retry_policy,
                join_policy,
                input_schema,
                output_schema,
            } => Self {
                kind: Some("workflow".to_string()),
                id,
                display_label,
                workflow_id: Some(workflow_id),
                acp_client,
                prompt,
                cwd,
                agent: None,
                agent_config,
                tool_mode: default_prompt_tool_mode(),
                topic: None,
                total_thoughts: default_total_thoughts(),
                tool_name: None,
                tool_args: None,
                model: None,
                thought_level: None,
                allowed_tools: None,
                max_turns: None,
                timeout,
                adopt,
                join_policy,
                requires_role,
                session_ref: None,
                retry_max_attempts: retry_policy.as_ref().map(|policy| policy.max_attempts),
                retry_backoff_min_ms: retry_policy.as_ref().map(|policy| policy.backoff_min_ms),
                retry_backoff_max_ms: retry_policy.as_ref().map(|policy| policy.backoff_max_ms),
                retry_jitter: retry_policy.as_ref().map(|policy| policy.jitter),
                input_schema,
                output_schema,
            },
            PipelineNode::Prompt {
                id,
                display_label,
                prompt,
                agent,
                tool_mode,
                model,
                thought_level,
                allowed_tools,
                max_turns,
                cwd,
                timeout,
                agent_config,
                adopt,
                requires_role,
                retry_policy,
                session_ref,
                join_policy,
                input_schema,
                output_schema,
            } => Self {
                kind: Some("prompt".to_string()),
                id,
                display_label,
                workflow_id: None,
                acp_client: None,
                prompt: Some(prompt),
                cwd,
                agent: Some(agent),
                agent_config,
                tool_mode,
                topic: None,
                total_thoughts: default_total_thoughts(),
                tool_name: None,
                tool_args: None,
                model,
                thought_level,
                allowed_tools,
                max_turns,
                timeout,
                adopt,
                join_policy,
                requires_role,
                session_ref,
                retry_max_attempts: retry_policy.as_ref().map(|policy| policy.max_attempts),
                retry_backoff_min_ms: retry_policy.as_ref().map(|policy| policy.backoff_min_ms),
                retry_backoff_max_ms: retry_policy.as_ref().map(|policy| policy.backoff_max_ms),
                retry_jitter: retry_policy.as_ref().map(|policy| policy.jitter),
                input_schema,
                output_schema,
            },
            PipelineNode::SequentialThinking {
                id,
                display_label,
                topic,
                total_thoughts,
                agent,
                model,
                thought_level,
                allowed_tools,
                max_turns,
                cwd,
                timeout,
                agent_config,
                adopt,
                requires_role,
                retry_policy,
                join_policy,
                input_schema,
                output_schema,
            } => Self {
                kind: Some("sequentialThinking".to_string()),
                id,
                display_label,
                workflow_id: None,
                acp_client: None,
                prompt: None,
                cwd,
                agent: Some(agent),
                agent_config,
                tool_mode: default_prompt_tool_mode(),
                topic: Some(topic),
                total_thoughts,
                tool_name: None,
                tool_args: None,
                model,
                thought_level,
                allowed_tools,
                max_turns,
                timeout,
                adopt,
                join_policy,
                requires_role,
                session_ref: None,
                retry_max_attempts: retry_policy.as_ref().map(|policy| policy.max_attempts),
                retry_backoff_min_ms: retry_policy.as_ref().map(|policy| policy.backoff_min_ms),
                retry_backoff_max_ms: retry_policy.as_ref().map(|policy| policy.backoff_max_ms),
                retry_jitter: retry_policy.as_ref().map(|policy| policy.jitter),
                input_schema,
                output_schema,
            },
            PipelineNode::Tool {
                id,
                display_label,
                tool_name,
                tool_args,
                agent,
                model,
                thought_level,
                allowed_tools,
                max_turns,
                cwd,
                timeout,
                agent_config,
                retry_policy,
                join_policy,
            } => Self {
                kind: Some("tool".to_string()),
                id,
                display_label,
                workflow_id: None,
                acp_client: None,
                prompt: None,
                cwd,
                agent,
                agent_config,
                tool_mode: default_prompt_tool_mode(),
                topic: None,
                total_thoughts: default_total_thoughts(),
                tool_name: Some(tool_name),
                tool_args,
                model,
                thought_level,
                allowed_tools,
                max_turns,
                timeout,
                join_policy,
                adopt: None,
                requires_role: None,
                session_ref: None,
                retry_max_attempts: retry_policy.as_ref().map(|policy| policy.max_attempts),
                retry_backoff_min_ms: retry_policy.as_ref().map(|policy| policy.backoff_min_ms),
                retry_backoff_max_ms: retry_policy.as_ref().map(|policy| policy.backoff_max_ms),
                retry_jitter: retry_policy.as_ref().map(|policy| policy.jitter),
                input_schema: None,
                output_schema: None,
            },
        }
    }
}
